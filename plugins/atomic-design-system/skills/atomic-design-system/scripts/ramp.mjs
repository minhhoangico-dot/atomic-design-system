#!/usr/bin/env node
// Generate a 50–950 color ramp from one brand hex in OKLCH, anchor the brand
// color exactly at its nearest step, and report WCAG contrast of every step
// against white and black so you can pick accessible semantic steps.
//
//   node ramp.mjs '#1C75BC'                       table
//   node ramp.mjs '#1C75BC' --name blue --prefix fdc --css   CSS custom properties
//   node ramp.mjs '#1C75BC' --json                JSON (DTCG-style $value)
//
// Why OKLCH: equal lightness steps look evenly spaced to the eye, unlike HSL,
// so step 600 of blue and step 600 of green have similar visual weight.

import { contrast, clampChroma, oklchToRgb, parseHex, rating, rgbToOklch, toHex } from './color.mjs';

const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const opt = (n, d) => {
  const i = args.indexOf(n);
  return i === -1 ? d : args[i + 1];
};
const hex = args.find((a) => /^#?[0-9a-f]{3,8}$/i.test(a));
if (!hex) {
  console.error("Usage: ramp.mjs '#RRGGBB' [--name blue] [--prefix ds] [--css|--json]");
  process.exit(2);
}

// Target OKLCH lightness per step. Light end stays usable as tinted
// backgrounds; 600–700 usually land near 4.5:1 against white.
const STEPS = { 50: 0.975, 100: 0.94, 200: 0.88, 300: 0.8, 400: 0.71, 500: 0.63, 600: 0.555, 700: 0.48, 800: 0.4, 900: 0.32, 950: 0.25 };

const base = parseHex(hex);
const [L0, C0, H0] = rgbToOklch(base);
const anchor = Object.entries(STEPS).reduce((best, [k, l]) =>
  Math.abs(l - L0) < Math.abs(STEPS[best] - L0) ? k : best, '500');

const ramp = Object.entries(STEPS).map(([step, L]) => {
  if (step === anchor) return { step, hex: toHex(base), anchor: true };
  // Chroma tapers toward the very light and very dark ends, as in most
  // hand-tuned palettes, then is clamped into the sRGB gamut.
  const span = L > L0 ? 1 - L0 : L0;
  const t = Math.min(1, Math.abs(L - L0) / Math.max(span, 0.05));
  const C = C0 * (1 - 0.75 * t * t);
  return { step, hex: toHex(oklchToRgb(clampChroma([L, C, H0]))) };
});

for (const r of ramp) {
  r.onWhite = contrast(r.hex, '#FFFFFF');
  r.onBlack = contrast(r.hex, '#000000');
}

const name = opt('--name', 'brand');
const prefix = opt('--prefix', 'ds');

if (flag('--css')) {
  console.log(`  /* ${name} ramp from ${toHex(base)} (anchored at ${anchor}); generated by ramp.mjs */`);
  for (const r of ramp) console.log(`  --${prefix}-color-${name}-${r.step}: ${r.hex};`);
} else if (flag('--json')) {
  const out = { color: { $type: 'color', [name]: {} } };
  for (const r of ramp) out.color[name][r.step] = { $value: r.hex, ...(r.anchor ? { $description: 'Brand source color' } : {}) };
  console.log(JSON.stringify(out, null, 2));
} else {
  console.log(`Ramp for ${toHex(base)}  OKLCH(${L0.toFixed(3)} ${C0.toFixed(3)} ${H0.toFixed(1)})  anchored at step ${anchor}\n`);
  console.log('step  hex       white-text-on-it      black-text-on-it');
  for (const r of ramp) {
    const w = `${r.onWhite.toFixed(2)} ${rating(r.onWhite)}`.padEnd(20);
    const b = `${r.onBlack.toFixed(2)} ${rating(r.onBlack)}`;
    console.log(`${r.step.padEnd(5)} ${r.hex}  ${w}  ${b}${r.anchor ? '   <- brand' : ''}`);
  }
  const firstAA = ramp.find((r) => r.onWhite >= 4.5);
  const firstAAA = ramp.find((r) => r.onWhite >= 7);
  console.log(`\nLightest step for white text / text on white: AA ${firstAA?.step ?? 'none'} (${firstAA?.hex ?? '-'}), AAA ${firstAAA?.step ?? 'none'} (${firstAAA?.hex ?? '-'})`);
}
